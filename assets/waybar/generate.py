#!/usr/bin/env python3
"""Generate koje's Waybar config with Lucide icons looked up by name
(ADR 0020). Run from the repo root: python3 assets/waybar/generate.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
cp = json.loads((root / "assets/fonts/lucide/codepoints.json").read_text())
out = Path(__file__).resolve().parent / "config.jsonc"


def i(name: str) -> str:
    """JSON escape for a Lucide icon, e.g. \\ue1ae – fails on unknown names."""
    return "\\u%04x" % cp[name]


config = f'''// koje's Waybar config with Lucide icons – generated by generate.py, do not edit.
// First draft of the bar configuration koje ships (M8.2, ADR 0020).
{{
  "layer": "top",
  "position": "top",
  "height": 28,
  "modules-left": ["custom/koje", "hyprland/workspaces", "hyprland/workspaces#tasks"],
  "modules-center": ["clock"],
  "modules-right": ["hyprland/language", "cpu", "memory", "pulseaudio", "network", "battery", "tray"],

  // Running contexts from kojed, also without windows (koje bar, M5.15).
  "custom/koje": {{
    "exec": "~/.local/bin/koje bar",
    "return-type": "json",
    "escape": false,
    "on-click": "~/.local/lib/koje/koje-context-picker"
  }},
  "hyprland/workspaces": {{ "format": "{{name}}" }},
  // The windows of the current workspace only (wlr/taskbar cannot filter by
  // workspace): the workspaces module's taskbar mode on the active one. A
  // stashed window is on a special workspace, so not listed. Click: focus.
  // Waybar (0.15) turns the taskbar on only when "format" has {{windows}}, and
  // reads on-click-window only inside workspace-taskbar.
  "hyprland/workspaces#tasks": {{
    "active-only": true,
    "format": "{{windows}}",
    "workspace-taskbar": {{
      "enable": true,
      "format": "{{icon}} {{title}}",
      "icon-size": 16,
      "on-click-window": "hyprctl dispatch focuswindow address:{{address}}"
    }}
  }},
  "clock": {{
    "format": "{i("clock")}  {{:%H:%M}}",                       // clock
    "format-alt": "{i("calendar")}  {{:%a %d.%m.%Y}}",          // calendar
    "tooltip-format": "<tt>{{calendar}}</tt>"
  }},
  // Keyboard layouts from hyprland.conf (kb_layout/kb_variant); click: the next one.
  "hyprland/language": {{
    "format": "{i("keyboard")}  {{long}}",
    "on-click": "hyprctl switchxkblayout all next"
  }},
  "cpu": {{ "format": "{i("cpu")}  {{usage}}%", "interval": 5 }},     // cpu
  "memory": {{ "format": "{i("memory-stick")}  {{percentage}}%", "interval": 5 }},  // memory-stick
  "pulseaudio": {{
    "format": "{i("volume-2")}  {{volume}}%",                    // volume-2
    "format-muted": "{i("volume-x")}  muted",                   // volume-x
    "on-click": "pavucontrol"
  }},
  "network": {{
    "format-wifi": "{i("wifi")}  {{essid}}",                     // wifi
    "format-ethernet": "{i("ethernet-port")}  {{ipaddr}}",       // ethernet-port
    "format-disconnected": "{i("wifi-off")}  offline",          // wifi-off
    "tooltip-format": "{{ifname}} {{ipaddr}}/{{cidr}}"
  }},
  "battery": {{
    "format": "{i("battery")}  {{capacity}}%",                   // battery
    "format-charging": "{i("battery-charging")}  {{capacity}}%"  // battery-charging
  }},
  "tray": {{ "spacing": 8 }}
}}
'''
out.write_text(config)
print("wrote", out)
